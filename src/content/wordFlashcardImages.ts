export const validWordImageKinds = [
  'object',
  'place',
  'person',
  'position',
  'quality',
  'action',
  'structure',
  'time',
  'abstract',
] as const;

export const validWordImageVisualStyles = ['concrete', 'scene', 'relation', 'grammar'] as const;

export type WordImageKind = (typeof validWordImageKinds)[number];
export type WordImageVisualStyle = (typeof validWordImageVisualStyles)[number];
export type WordImageLabelPolicy = 'none' | 'english-keyword';

export interface WordImageAsset {
  wordId: string;
  image: string;
  kind: WordImageKind;
  visualStyle: WordImageVisualStyle;
  labelPolicy: WordImageLabelPolicy;
  prompt: string;
}

function wordImageAsset(
  wordId: string,
  image: string,
  kind: WordImageKind,
  visualStyle: WordImageVisualStyle,
  labelPolicy: WordImageLabelPolicy,
  prompt: string,
): WordImageAsset {
  const aliases: Record<string, string> = { mistake: 'chemical', choice: 'copper', command: 'coal', warning: 'church', result: 'cotton', worry: 'bridge' };
  return { wordId: aliases[wordId] ?? wordId, image, kind, visualStyle, labelPolicy, prompt };
}

